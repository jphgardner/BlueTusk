using Microsoft.EntityFrameworkCore;

namespace BlueTusk.EntityFrameworkCore.CompatibilityTests;

[Trait("Category", "PostgreSqlCompatibility")]
public sealed class PostgreSqlProviderCompatibilityTests
{
    private static readonly int[] ExpectedSeries = [3, 5, 7];
    private static readonly string[] ExpectedDistinctLabels = ["alpha", "beta", "skip"];

    [PostgreSqlFact]
    public async Task SaveChanges_reads_generated_keys_and_detects_conflicting_updates()
    {
        await using var context = CreateContext();
        await context.Database.OpenConnectionAsync();
        await using var transaction = await context.Database.BeginTransactionAsync();
        await CreateTemporaryTable(context);

        var first = new Row { Label = "first", Json = "[]" };
        var second = new Row { Label = "second", Json = "[]" };
        context.Rows.AddRange(first, second);
        Assert.Equal(2, await context.SaveChangesAsync());
        Assert.True(first.Id > 0 && second.Id > 0);
        Assert.NotEqual(first.Id, second.Id);

        first.Label = "updated first";
        second.Label = "updated second";
        Assert.Equal(2, await context.SaveChangesAsync());
        var reloaded = await context.Rows.AsNoTracking().SingleAsync(row => row.Id == first.Id);
        Assert.Equal(first.Label, reloaded.Label);

        context.Rows.Remove(second);
        Assert.Equal(1, await context.SaveChangesAsync());
        Assert.Single(await context.Rows.AsNoTracking().ToListAsync());

        await context.Database.ExecuteSqlRawAsync(
            """UPDATE compatibility_live_rows SET "Label" = 'changed elsewhere' WHERE "Id" = {0}""", first.Id);
        first.Label = "conflicting write";
        await Assert.ThrowsAsync<DbUpdateConcurrencyException>(() => context.SaveChangesAsync());
    }

    [PostgreSqlFact]
    public async Task Reads_composed_series_and_correlated_json_recordsets()
    {
        await using var context = CreateContext();
        await context.Database.OpenConnectionAsync();
        await using var transaction = await context.Database.BeginTransactionAsync();
        await CreateTemporaryTable(context);
        context.Rows.Add(new Row { Label = "seed", Json = "[{\"Id\":7,\"Label\":\"seven\"}]" });
        await context.SaveChangesAsync();

        var series = await context.Database.GenerateSeries(1, 7, 2)
            .Where(value => value > 1).OrderBy(value => value).ToListAsync();
        Assert.Equal(ExpectedSeries, series);

        var found = await context.Rows.SelectMany(row => EF.Functions.JsonToRecordset<JsonRow>(row.Json))
            .Where(row => row.Id > 5).SingleAsync();
        Assert.Equal("seven", found.Label);
    }

    [PostgreSqlFact]
    public async Task Executes_grouped_aggregates_with_distinct_filter_and_ordering()
    {
        await using var context = CreateContext();
        await context.Database.OpenConnectionAsync();
        await using var transaction = await context.Database.BeginTransactionAsync();
        await CreateTemporaryTable(context);
        context.Rows.AddRange(
            new Row { Label = "alpha", Json = "[]" },
            new Row { Label = "skip", Json = "[]" },
            new Row { Label = "beta", Json = "[]" },
            new Row { Label = "beta", Json = "[]" });
        await context.SaveChangesAsync();

        var includeLabels = true;
        var labels = await context.Rows.GroupBy(row => row.Json)
            .Select(group => new
            {
                Ordered = EF.Functions.StringAggregate(group.Distinct().Where(row => row.Label != "skip")
                    .OrderByDescending(row => row.Label).ThenBy(row => row.Id).Select(row => row.Label), ","),
                Distinct = EF.Functions.ArrayAggregate(group.Where(_ => includeLabels)
                    .Select(row => row.Label).Distinct().OrderBy(label => label)),
            })
            .SingleAsync();

        Assert.Equal("beta,beta,alpha", labels.Ordered);
        Assert.Equal(ExpectedDistinctLabels, labels.Distinct);

        var preselectedLabels = await context.Rows.GroupBy(row => row.Json, row => row.Label)
            .Select(group => EF.Functions.StringAggregate(group.OrderBy(label => label), ","))
            .SingleAsync();

        Assert.Equal("alpha,beta,beta,skip", preselectedLabels);
    }

    private static CompatibilityContext CreateContext() => new(new DbContextOptionsBuilder<CompatibilityContext>()
        .UseBlueTusk(Environment.GetEnvironmentVariable(PostgreSqlFactAttribute.ConnectionStringVariable)!).Options);

    private static Task<int> CreateTemporaryTable(CompatibilityContext context) => context.Database.ExecuteSqlRawAsync(
        """
        CREATE TEMPORARY TABLE compatibility_live_rows (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "Label" text NOT NULL,
            "Json" jsonb NOT NULL
        ) ON COMMIT DROP
        """);

    private sealed class CompatibilityContext(DbContextOptions<CompatibilityContext> options) : DbContext(options)
    {
        public DbSet<Row> Rows => Set<Row>();

        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            modelBuilder.Entity<Row>(entity =>
            {
                entity.ToTable("compatibility_live_rows");
                entity.Property(row => row.Label).IsConcurrencyToken();
                entity.Property(row => row.Json).HasColumnType("jsonb");
            });
            modelBuilder.Entity<JsonRow>().HasNoKey().ToTable("compatibility_live_json_rows");
        }
    }

    private sealed class Row
    {
        public int Id { get; set; }
        public string Label { get; set; } = string.Empty;
        public string Json { get; set; } = string.Empty;
    }

    private sealed class JsonRow
    {
        public int Id { get; set; }
        public string Label { get; set; } = string.Empty;
    }
}
